/** Translate a key. Optional $fallback and sprintf-style $args. */
function t(string $key, ?string $fallback = null, array $args = []): string
{
    $l = current_locale();
    $text = translations()[$l][$key] ?? $fallback ?? $key;
    return $args ? vsprintf($text, $args) : $text;
}

/** Translate a dynamic database value (status, type, channel...) safely. */
function tx_label(string $value): string
{
    $value = trim($value);
    if ($value === '') return $value;
    // snake_case -> Title case with spaces, then translate (falls back to the
    // humanised value when no translation exists).
    $key = str_replace('_', ' ', ucfirst($value));
    $l = current_locale();
    $map = translations()[$l] ?? [];
    return $map[$key] ?? $key;
}


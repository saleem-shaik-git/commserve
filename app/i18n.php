function language_selector(string $class = 'form-select form-select-sm'): string
{
    $h = '<form method="post" action="' . e(url('language.php')) . '" class="d-inline-flex align-items-center gap-2">' . csrf_field() . '<select name="locale" class="' . e($class) . '" onchange="this.form.submit()" aria-label="' . e(t('Language')) . '">';
    foreach (LOCALE_LABELS as $c => $label) $h .= '<option value="' . e($c) . '"' . (current_locale() === $c ? ' selected' : '') . '>' . e($label) . '</option>';
    return $h . '</select></form>';
}
